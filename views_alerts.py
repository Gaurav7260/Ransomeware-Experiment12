"""Alert Center View for CanarySentinel Dashboard."""

from typing import Any, Dict
import pandas as pd
import streamlit as st

from canary_sentinel.detection.explanation_engine import DetectionExplanationEngine
from canary_sentinel.storage.db import Database


def render_alert_center(services: Dict[str, Any], is_technical: bool = False) -> None:
    """Render Section 5: Alert Center & Incident Forensics."""
    st.title("🚨 Alert Center & Incident Forensics")
    st.caption("Evidence-backed security incidents generated by the three detection configurations.")

    db: Database = services["db"]

    # Filter controls
    a_c1, a_c2, a_c3 = st.columns(3)
    with a_c1:
        det_filter = st.selectbox("Detector Configuration", ["ALL", "baseline", "canary_only", "hybrid"], index=0)
    with a_c2:
        sev_filter = st.selectbox("Severity Level", ["ALL", "CRITICAL", "HIGH", "MEDIUM", "LOW"], index=0)
    with a_c3:
        limit_val = st.slider("Max Alerts to Display", min_value=10, max_value=200, value=50, step=10)

    alerts = db.get_alerts(
        limit=limit_val,
        detector_config=None if det_filter == "ALL" else det_filter,
    )
    if sev_filter != "ALL":
        alerts = [a for a in alerts if a.severity == sev_filter]

    st.subheader(f"Incidents Log ({len(alerts)} records)")

    if alerts:
        alert_rows = []
        for a in alerts:
            alert_rows.append({
                "Alert ID": a.alert_id[:8] + "...",
                "Timestamp": a.iso_timestamp,
                "Detector": a.detector_config.replace("_", " ").title(),
                "Severity": a.severity,
                "Risk Score": f"{a.risk_score}/100",
                "Confidence": f"{a.confidence:.0%}",
                "Trigger Summary": a.triggering_event_summary,
                "Containment Action": a.response_status,
                "Scenario ID": a.scenario_id or "-",
            })

        df_alerts = pd.DataFrame(alert_rows)
        st.dataframe(df_alerts, use_container_width=True)

        st.markdown("---")
        st.subheader("🔍 Deep-Dive Incident Explanation & Forensic Evidence")
        selected_idx = st.selectbox(
            "Select an Incident to Inspect with the Detection Explanation Engine:",
            range(len(alerts)),
            format_func=lambda i: f"[{alerts[i].severity}] {alerts[i].detector_config.upper()} - {alerts[i].triggering_event_summary} ({alerts[i].iso_timestamp.split('T')[-1]})",
        )

        selected_alert = alerts[selected_idx]
        detail = DetectionExplanationEngine.explain_alert(selected_alert)

        card_col1, card_col2 = st.columns([2, 1])
        with card_col1:
            st.markdown(f"### {detail.headline}")
            st.markdown(f"**What happened?**\n{detail.what_happened}")
            st.markdown(f"**Why was it flagged as suspicious?**\n{detail.why_suspicious}")

            st.markdown("**Corroborating Evidence:**")
            for ev in detail.observed_evidence:
                st.markdown(f"- `{ev}`")

            st.markdown(f"**Detector Inference:**\n{detail.detector_inference}")
            st.markdown(f"**Analyst Recommendation:**\n{detail.recommended_action}")

        with card_col2:
            st.metric("Risk Score", f"{selected_alert.risk_score} / 100")
            st.metric("Detection Confidence", f"{selected_alert.confidence:.0%}")
            st.metric("Containment Status", selected_alert.response_status)
            st.caption(f"Supporting Events in Window: {len(selected_alert.supporting_event_ids)}")
            st.info(f"**Containment Protocol:**\n{detail.containment_status}")

        if is_technical:
            with st.expander("🔬 Raw Alert Telemetry (JSON Payload)", expanded=False):
                st.json(selected_alert.to_dict())

    else:
        st.info("No security alerts matching current filter criteria. Run an attack scenario in the **Live Test Lab** to generate alerts.")

